/** บริบทของโฟลเดอร์ (ถ้าคุยในโหมดโฟลเดอร์) — ทำหน้าที่เหมือน nearby_communities / retrieved_context */
export interface FolderContext {
  folderName: string;
  /** รายชื่อสถานที่/ชุมชนจากคลิปที่เซฟไว้ */
  places: string[];
}

export function buildChatSystemPrompt(folder?: FolderContext): string {
  if (!folder || folder.places.length === 0) return CHAT_SYSTEM_PROMPT;
  return `${CHAT_SYSTEM_PROMPT}

[Context จากระบบ — ใช้เป็นแหล่งข้อมูลหลัก]
ผู้ใช้กำลังคุยจากโฟลเดอร์คลิปที่บันทึกไว้ชื่อ "${folder.folderName}"
สถานที่/ชุมชนจากคลิปในโฟลเดอร์นี้ (ถือเป็น nearby_communities ที่ผู้ใช้สนใจ):
${folder.places.map((p, i) => `${i + 1}. ${p}`).join("\n")}

เมื่อแนะนำหรือวางแผน ให้ยึดสถานที่เหล่านี้เป็นหลัก และอย่าแต่งข้อมูลราคา/เบอร์/ที่อยู่ที่ไม่มีอยู่จริง`;
}

// ---------- 2) TRIP PLANNER ----------
export interface TripRequest {
  startPoint: string; // จุดเริ่มต้น เช่น "สนามบินเชียงใหม่"
  destinations: string[]; // ปลายทาง/ชุมชนจากคลิป
  days: number; // จำนวนวัน
  nights: number;
  budgetPerPerson: number; // งบต่อคน (บาท)
  style: string; // สไตล์ เช่น "โร้ดทริปเน้นธรรมชาติ"
}

export const TRIP_SYSTEM_PROMPT = `คุณคือ AI นักวางแผนโร้ดทริปของแอป Local
วัตถุประสงค์: แปลงรายการสถานที่ให้กลายเป็นเส้นทางขับรถจริง ที่ไม่ขับวน คุมงบได้ และสมจริง

กติกา:
- จัดลำดับจุดแวะให้เส้นทางต่อเนื่อง ไม่ย้อนไปมา (optimize ตามภูมิศาสตร์โดยประมาณ)
- แต่ละวันระบุ: จุดแวะ, เวลาโดยประมาณที่ใช้ที่จุดนั้น (ชั่วโมง), และระยะเวลาขับรถไปจุดถัดไป (นาที/ชั่วโมง)
- เกลี่ยงบ (ที่พัก + ค่าน้ำมัน + ค่าอาหาร) ไม่ให้เกินเพดานงบต่อคน
- สมเหตุสมผลกับจำนวนวัน/คืน และสไตล์การเดินทางที่เลือก
- ตอบกลับเป็น JSON ตามรูปแบบที่กำหนดเท่านั้น ห้ามมีข้อความอื่นนอก JSON`;

export function buildTripPrompt(req: TripRequest): string {
  return `โปรดวางแผนโร้ดทริปจากข้อมูลต่อไปนี้

จุดเริ่มต้น: ${req.startPoint}
ปลายทาง/จุดแวะที่สนใจ: ${req.destinations.join(", ") || "(ยังไม่ระบุ ให้แนะนำตามจุดเริ่มต้น)"}
ระยะเวลา: ${req.days} วัน ${req.nights} คืน
งบประมาณต่อคน: ไม่เกิน ${req.budgetPerPerson.toLocaleString()} บาท
สไตล์การเดินทาง: ${req.style}

ตอบกลับเป็น JSON รูปแบบนี้เท่านั้น:
{
  "title": "ชื่อทริปสั้นๆ",
  "summary": "สรุปทริป 1-2 ประโยค",
  "days": [
    {
      "day": 1,
      "stops": [
        {
          "name": "ชื่อจุดแวะ",
          "activity": "ทำอะไรที่นี่",
          "stayHours": 2,
          "driveToNextMins": 90
        }
      ]
    }
  ],
  "budget": {
    "lodging": 0,
    "fuel": 0,
    "food": 0,
    "total": 0,
    "perPerson": 0,
    "withinBudget": true
  }
}`;
}
