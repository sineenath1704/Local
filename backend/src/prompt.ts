/** ชนิดเสียงในคลิป (ตาม Video Content Analyzer spec) */
export type AudioType = "speech" | "music" | "mixed" | "none";

/** ข้อมูลที่ได้จากขั้น Speech-to-Text + Vision ก่อนส่งเข้า LLM */
export interface VideoAnalysisInput {
  /** แคปชันที่ผู้โพสต์เขียน */
  caption?: string;
  /** ข้อความถอดเสียงจากคลิป (Speech-to-Text) */
  transcript?: string;
  /** ชนิดเสียง: speech | music | mixed | none */
  audioType?: AudioType;
  /** คำอธิบายภาพจาก Vision AI */
  visualDescription?: string;
  /** ตัวหนังสือ/ป้าย/ซับไตเติลในคลิป */
  onScreenText?: string[];
  /** ความยาวคลิป (วินาที) */
  videoDurationSec?: number;
  /** ผู้โพสต์เป็นชุมชนหรือนักท่องเที่ยว */
  uploaderType?: "community" | "tourist";
  /** ข้อมูลประกอบเพิ่มเติม (ถ้ามี) */
  location?: string;
  /** Public URL ของวิดีโอ — เมื่อมี จะส่งคลิปให้ M3 วิเคราะห์ภาพ+ข้อความบนจอโดยตรง */
  videoUrl?: string;
  /**
   * โหมดย่อ — ใช้เมื่อรอบเต็มโดนปลายทางตอบ 504 (หมดเวลา)
   * -------------------------------------------------------------
   * ขอ JSON ที่เล็กลงมาก (ไม่มี reasoning, ไม่มี scene_inventory,
   * visual_description ไม่เกิน 3 ประโมก) → โมเดลตอบจบก่อนที่
   * proxy ของปลายทางจะตัดการเชื่อมต่อ
   */
  compact?: boolean;
}

