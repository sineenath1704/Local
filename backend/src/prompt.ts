/**
 * ตรวจคำบรรยายหลัง Stage 2 ก่อนส่งให้ผู้ใช้
 * คืนรายการปัญหา — ว่าง = ผ่าน ถ้าไม่ผ่านให้เรียก Stage 2 ซ้ำ 1 รอบ
 * ตัวอย่าง: const problems = validateNarration(text, inventory, place);
 *           if (problems.length) text = await runNarrationAgain();
 */
export function validateNarration(
  text: string,
  inventory: any[],
  place: any
): string[] {
  const problems: string[] = [];
  const paras = text.trim().split(/\n\s*\n/).filter(Boolean);

  // ย่อหน้า 2 ย่อหน้า + บรรทัดลายน้ำ (ถ้ามี) ได้สูงสุด 3 ก้อน
  if (paras.length < 2) problems.push("ย่อหน้าไม่ครบ 2");
  if (paras.length > 3) problems.push("ย่อหน้าเกิน");

  const p1 = paras[0] ?? "";
  const p2 = paras[1] ?? "";

  if (!p2.startsWith("ก่อนตัดสินใจไป")) {
    problems.push("ย่อหน้า 2 ไม่ได้ขึ้นต้นด้วย 'ก่อนตัดสินใจไป'");
  }

  // ของใน inventory ต้องถูกเอ่ยถึง (ตัวกรองหยาบจากคำหน้าของ item)
  const missing = (inventory ?? []).filter(
    (it) => it?.item && !p1.includes(String(it.item).slice(0, 4))
  );
  if (missing.length > 2) problems.push(`ตกรายการ ${missing.length} ชิ้น`);

  // ตัวเลขราคาต้องตรงข้อมูล
  const priceNums =
    JSON.stringify(place?.price_info ?? {}).match(/\d[\d,]*/g) ?? [];
  for (const n of priceNums) {
    if (!text.includes(n)) {
      problems.push(`ราคา ${n} ไม่อยู่ในคำบรรยาย`);
      break;
    }
  }

  // ย่อหน้า 2 ซ้ำย่อหน้า 1 มากเกินไป (เทียบชิ้นข้อความ 6 ตัวอักษร) ปรับเกณฑ์ได้
  const shingles = (s: string) => {
    const out = new Set<string>();
    for (let i = 0; i + 6 <= s.length; i++) out.add(s.slice(i, i + 6));
    return out;
  };
  const s1 = shingles(p1);
  const s2 = shingles(p2);
  if (s2.size > 0) {
    let overlap = 0;
    s2.forEach((g) => {
      if (s1.has(g)) overlap++;
    });
    if (overlap / s2.size > 0.25) problems.push("ย่อหน้า 2 ซ้ำย่อหน้า 1");
  }

  return problems;
}

