function pickParagraph2Order(category: unknown): string {
  const list = Array.isArray(category) ? category.map((c) => String(c)) : [];
  for (const c of list) {
    const hit = PARAGRAPH2_MODULES.find((m) => m.keys.some((k) => c.includes(k)));
    if (hit) return hit.order;
  }
  return PARAGRAPH2_DEFAULT_ORDER;
}

/** ตัดค่าว่าง (null, "", [], {}) ออกจาก JSON ก่อนส่งให้โมเดล เพื่อไม่ให้โมเดลไปเล่าสิ่งที่ไม่มี */
function pruneEmpty(v: any): any {
  if (v === null || v === undefined) return undefined;
  if (typeof v === "string") {
    const t = v.trim();
    return t === "" || t.toLowerCase() === "null" ? undefined : v;
  }
  if (Array.isArray(v)) {
    const arr = v.map(pruneEmpty).filter((x) => x !== undefined);
    return arr.length ? arr : undefined;
  }
  if (typeof v === "object") {
    const out: any = {};
    for (const [k, val] of Object.entries(v)) {
      const p = pruneEmpty(val);
      if (p !== undefined) out[k] = p;
    }
    return Object.keys(out).length ? out : undefined;
  }
  return v;
}

